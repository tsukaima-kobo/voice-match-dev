/** ランダムに 1 つ（前と同じ物は避ける） */
export function nextPrompt(prev: string | null, random: () => number = Math.random): string {
  if (PROMPTS.length < 2) return PROMPTS[0]!;
  for (;;) {
    const p = PROMPTS[Math.floor(random() * PROMPTS.length)]!;
    if (p !== prev) return p;
  }
}
